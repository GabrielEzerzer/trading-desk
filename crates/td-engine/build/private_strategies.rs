//! Turns a folder of strategy files into Rust source that compiles them into td-engine and lists
//! their entries with the hash of each file. build.rs runs it on the private strategies folder;
//! the crate's tests run it on fixture folders. [`example_hashes`] gives the example strategies'
//! hashes the same way.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

/// The first 16 hex digits of the SHA-256 of a strategy's source file, with each CRLF read as LF so
/// a checkout that converts line endings hashes the same as one that does not. A saved run and
/// verdict record it, so a verdict can tell when its strategy's code has changed.
///
/// shortcut: the hash covers the strategy's own file only. Any other file it uses is not hashed:
/// shared helpers (such as `strategies/mod.rs`, `gotobi_calendar.rs` or the engine itself), and
/// also a file of its own that it pulls in with `#[path]` or `include!`. A change to any of those
/// alone leaves `code_matches` true and `code_versions` unchanged. Hash those files too if
/// strategies come to keep logic that decides their trades outside their own file.
pub fn source_hash(path: &Path) -> Result<String, String> {
    let bytes = fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut normalised = Vec::with_capacity(bytes.len());
    for (i, &b) in bytes.iter().enumerate() {
        if !(b == b'\r' && bytes.get(i + 1) == Some(&b'\n')) {
            normalised.push(b);
        }
    }
    let digest = Sha256::digest(&normalised);
    Ok(digest[..8].iter().map(|b| format!("{b:02x}")).collect())
}

/// The `*.rs` files directly in `dir`, sorted, skipping names that start with a dot (editor
/// backups). A missing `dir` has none.
fn rust_files(dir: &Path) -> Result<Vec<PathBuf>, String> {
    let mut files: Vec<PathBuf> = Vec::new();
    match fs::read_dir(dir) {
        Err(e) if e.kind() == io::ErrorKind::NotFound => {}
        Err(e) => return Err(format!("{}: {e}", dir.display())),
        Ok(entries) => {
            for entry in entries {
                let path = entry.map_err(|e| format!("{}: {e}", dir.display()))?.path();
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if path.is_file() && name.ends_with(".rs") && !name.starts_with('.') {
                    files.push(path);
                }
            }
        }
    }
    files.sort();
    Ok(files)
}

/// Source declaring one constant per `*.rs` file in `dir`, the examples folder: its stem in upper
/// case holding [`source_hash`] of the file, such as `SMA_CROSS` for `sma_cross.rs`.
pub fn example_hashes(dir: &Path) -> Result<String, String> {
    let mut source = format!(
        "// Generated by td-engine's build.rs from {}. Do not edit.\n",
        dir.display()
    );
    for path in rust_files(dir)? {
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if !is_module_name(stem) {
            continue;
        }
        source.push_str(&format!(
            "#[allow(dead_code)]\npub(crate) const {}: &str = {:?};\n",
            stem.to_ascii_uppercase(),
            source_hash(&path)?
        ));
    }
    Ok(source)
}

/// Rust's strict and reserved keywords in the 2024 edition. None of them can name a module.
const KEYWORDS: &[&str] = &[
    // strict
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type",
    "unsafe", "use", "where", "while", // reserved
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try", "typeof",
    "unsized", "virtual", "yield",
];

/// Whether `stem` can be written as `mod stem;`: lowercase ASCII letters, digits and
/// underscores, not starting with a digit, not a bare `_` and not a keyword.
fn is_module_name(stem: &str) -> bool {
    stem.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
        && stem
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && stem != "_"
        && !KEYWORDS.contains(&stem)
}

/// Source declaring one module per `*.rs` file directly in `dir`, by its absolute path, an
/// `entries()` function listing each module's `entry()`, in file name order, and `CODE_HASHES`,
/// each file's [`source_hash`] in the same order. A missing `dir` gives empty lists. Files whose
/// name starts with a dot (editor backups) are skipped; any other file name must be a module name
/// such as `my_strategy.rs`, and not a Rust keyword or `_`.
pub fn generate(dir: &Path) -> Result<String, String> {
    let files = rust_files(dir)?;
    let mut modules = String::new();
    let mut calls = Vec::new();
    let mut hashes = Vec::new();
    for path in &files {
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if !is_module_name(stem) {
            return Err(format!(
                "{}: a strategy file's name must be a Rust module name such as my_strategy.rs, \
                 and not a Rust keyword or _",
                path.display()
            ));
        }
        let path_text = path
            .to_str()
            .ok_or_else(|| format!("{}: the path is not UTF-8", path.display()))?;
        modules.push_str(&format!("#[path = {path_text:?}]\nmod {stem};\n"));
        calls.push(format!("{stem}::entry()"));
        hashes.push(format!("{:?}", source_hash(path)?));
    }
    let list = if calls.is_empty() {
        "Vec::new()".to_string()
    } else {
        format!("vec![{}]", calls.join(", "))
    };
    Ok(format!(
        "// Generated by td-engine's build.rs from {}. Do not edit.\n\
         {modules}\n\
         pub(crate) fn entries() -> Vec<crate::StrategyEntry> {{\n    {list}\n}}\n\n\
         pub(crate) const CODE_HASHES: &[&str] = &[{}];\n",
        dir.display(),
        hashes.join(", ")
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_missing_folder_lists_no_strategies() {
        let dir = tempfile::tempdir().unwrap();
        let source = generate(&dir.path().join("private")).unwrap();
        assert!(!source.contains("mod "), "{source}");
        assert!(
            source.contains(
                "pub(crate) fn entries() -> Vec<crate::StrategyEntry> {\n    Vec::new()\n}"
            ),
            "{source}"
        );
    }

    #[test]
    fn each_strategy_file_becomes_a_module_and_an_entry() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        for name in ["zeta.rs", "my_strategy.rs", "README.md", ".#my_strategy.rs"] {
            fs::write(root.join(name), "").unwrap();
        }
        fs::create_dir(root.join("helpers.rs")).unwrap();
        let source = generate(root).unwrap();
        let path = |name: &str| format!("{:?}", root.join(name).to_str().unwrap());
        assert!(
            source.contains(&format!(
                "#[path = {}]\nmod my_strategy;\n",
                path("my_strategy.rs")
            )),
            "{source}"
        );
        assert!(
            source.contains(&format!("#[path = {}]\nmod zeta;\n", path("zeta.rs"))),
            "{source}"
        );
        assert!(
            source.contains("vec![my_strategy::entry(), zeta::entry()]"),
            "{source}"
        );
        assert_eq!(source.matches("mod ").count(), 2, "{source}");
        // Both files are empty, so they hash the same.
        let empty = source_hash(&root.join("zeta.rs")).unwrap();
        assert!(
            source.contains(&format!(
                "pub(crate) const CODE_HASHES: &[&str] = &[{empty:?}, {empty:?}];"
            )),
            "{source}"
        );
    }

    /// A strategy's hash changes with its code but not with its line endings, so a checkout that
    /// writes CRLF hashes the same as CI's LF one.
    #[test]
    fn the_hash_follows_the_code_and_ignores_line_endings() {
        let dir = tempfile::tempdir().unwrap();
        let write = |name: &str, text: &str| {
            let path = dir.path().join(name);
            fs::write(&path, text).unwrap();
            source_hash(&path).unwrap()
        };
        let lf = write("lf.rs", "fn a() {}\nfn b() {}\n");
        assert_eq!(lf.len(), 16);
        assert_eq!(write("crlf.rs", "fn a() {}\r\nfn b() {}\r\n"), lf);
        assert_ne!(write("edited.rs", "fn a() {}\nfn c() {}\n"), lf);
        let examples = example_hashes(dir.path()).unwrap();
        assert!(
            examples.contains(&format!("pub(crate) const LF: &str = {lf:?};")),
            "{examples}"
        );
    }

    #[test]
    fn a_file_name_that_is_not_a_module_name_is_an_error() {
        let names = [
            "My-Strategy.rs",
            "2fast.rs",
            "MyStrategy.rs",
            "_.rs",
            "mod.rs",
            "type.rs",
            "match.rs",
            "self.rs",
            "Self.rs",
            "super.rs",
            "crate.rs",
            "gen.rs",
            "yield.rs",
        ];
        for name in names {
            let dir = tempfile::tempdir().unwrap();
            fs::write(dir.path().join(name), "").unwrap();
            let err = generate(dir.path()).unwrap_err();
            assert!(err.contains(name), "{err}");
        }
    }

    #[test]
    fn module_names_exclude_keywords_but_not_names_that_contain_them() {
        for good in [
            "my_strategy",
            "_private",
            "typed",
            "mod_cross",
            "self_test",
            "r2",
            "union",
        ] {
            assert!(is_module_name(good), "{good}");
        }
        for bad in [
            "", "_", "mod", "type", "match", "self", "Self", "super", "crate", "async",
        ] {
            assert!(!is_module_name(bad), "{bad}");
        }
        assert!(KEYWORDS.iter().all(|k| !is_module_name(k)));
    }
}
