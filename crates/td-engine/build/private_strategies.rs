//! Turns a folder of strategy files into Rust source that compiles them into td-engine and lists
//! their entries. build.rs runs it on the private strategies folder; the crate's tests run it on
//! fixture folders.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Source declaring one module per `*.rs` file directly in `dir`, by its absolute path, and an
/// `entries()` function listing each module's `entry()`, in file name order. A missing `dir`
/// gives an empty list. Files whose name starts with a dot (editor backups) are skipped; any other
/// file name must be a module name such as `my_strategy.rs`.
pub fn generate(dir: &Path) -> Result<String, String> {
    let mut files: Vec<PathBuf> = Vec::new();
    match fs::read_dir(dir) {
        Err(e) if e.kind() == io::ErrorKind::NotFound => {}
        Err(e) => return Err(format!("{}: {e}", dir.display())),
        Ok(entries) => {
            for entry in entries {
                let path = entry.map_err(|e| format!("{}: {e}", dir.display()))?.path();
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if path.is_file() && name.ends_with(".rs") && !name.starts_with('.') {
                    files.push(path);
                }
            }
        }
    }
    files.sort();
    let mut modules = String::new();
    let mut calls = Vec::new();
    for path in &files {
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        let valid = stem.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
            && stem
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
        if !valid {
            return Err(format!(
                "{}: a strategy file's name must be a Rust module name such as my_strategy.rs",
                path.display()
            ));
        }
        let path_text = path
            .to_str()
            .ok_or_else(|| format!("{}: the path is not UTF-8", path.display()))?;
        modules.push_str(&format!("#[path = {path_text:?}]\nmod {stem};\n"));
        calls.push(format!("{stem}::entry()"));
    }
    let list = if calls.is_empty() {
        "Vec::new()".to_string()
    } else {
        format!("vec![{}]", calls.join(", "))
    };
    Ok(format!(
        "// Generated by td-engine's build.rs from {}. Do not edit.\n\
         {modules}\n\
         pub(crate) fn entries() -> Vec<crate::StrategyEntry> {{\n    {list}\n}}\n",
        dir.display()
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_missing_folder_lists_no_strategies() {
        let dir = tempfile::tempdir().unwrap();
        let source = generate(&dir.path().join("private")).unwrap();
        assert!(!source.contains("mod "), "{source}");
        assert!(
            source.contains(
                "pub(crate) fn entries() -> Vec<crate::StrategyEntry> {\n    Vec::new()\n}"
            ),
            "{source}"
        );
    }

    #[test]
    fn each_strategy_file_becomes_a_module_and_an_entry() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        for name in ["zeta.rs", "my_strategy.rs", "README.md", ".#my_strategy.rs"] {
            fs::write(root.join(name), "").unwrap();
        }
        fs::create_dir(root.join("helpers.rs")).unwrap();
        let source = generate(root).unwrap();
        let path = |name: &str| format!("{:?}", root.join(name).to_str().unwrap());
        assert!(
            source.contains(&format!(
                "#[path = {}]\nmod my_strategy;\n",
                path("my_strategy.rs")
            )),
            "{source}"
        );
        assert!(
            source.contains(&format!("#[path = {}]\nmod zeta;\n", path("zeta.rs"))),
            "{source}"
        );
        assert!(
            source.contains("vec![my_strategy::entry(), zeta::entry()]"),
            "{source}"
        );
        assert_eq!(source.matches("mod ").count(), 2, "{source}");
    }

    #[test]
    fn a_file_name_that_is_not_a_module_name_is_an_error() {
        for name in ["My-Strategy.rs", "2fast.rs", "MyStrategy.rs"] {
            let dir = tempfile::tempdir().unwrap();
            fs::write(dir.path().join(name), "").unwrap();
            let err = generate(dir.path()).unwrap_err();
            assert!(err.contains(name), "{err}");
        }
    }
}
